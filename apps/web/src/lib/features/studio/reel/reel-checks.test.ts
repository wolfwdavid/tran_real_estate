import { describe, expect, it } from 'vitest';
import { RESULTS_PLACEHOLDER } from '@tran/core/studio';
import { computeGate, runChecks } from '$lib/ai/ui/panel-controller';
import { numberPostCheck, reelAllowedNumbers } from '../post-checks';
import { REEL_CHECKLIST, REEL_CHECKLIST_FOOTNOTE } from './checklist';
import {
	QUOTE_CATEGORY,
	QUOTE_EXPLANATION,
	REEL_CHECKERS,
	RESULTS_BEAT_CATEGORY,
	RESULTS_BEAT_EXPLANATION,
	quotePostCheck,
	resultsBeatPostCheck
} from './reel-checks';
import { formatReelForExit, reelFooter } from './reel-export';

const SECTION_SIGN = String.fromCharCode(0xa7);

const EXPECTED_CHECKLIST = [
	'I wrote or edited this script myself. AI helped draft it.',
	`If the video shows a person generated by AI, such as an avatar or digital presenter, I add a clear on-screen note like "This ad includes an AI-generated person." New York law requires this for ads seen in New York (General Business Law ${SECTION_SIGN} 396-b).`,
	`If I use an AI copy of my own face or voice, I turn on the platform's AI label, such as "AI info" on Instagram and Facebook.`,
	"Every result I mention is real, mine, and something I can show records for. I don't promise future profits or rising prices.",
	"Any client quote is real and used with that client's permission. No made-up quotes or reviews.",
	'My brokerage name and my license details appear in the caption or on screen, as my state requires.',
	'I describe homes and places, never the kind of people who should live there.',
	'I have the rights to the music, footage, and photos I use.'
];

function script(results: string): string {
	return [
		'HOOK',
		'Voiceover: I used to lose messages in my inbox.',
		'Caption: I used to lose messages',
		'B-roll: Close-up of a phone with unread messages',
		'',
		'MANUAL PAIN',
		'Voiceover: I tracked every showing request on paper.',
		'Caption: Every request on paper',
		'B-roll: Desk covered in paper notes',
		'',
		'BEFORE AND AFTER',
		'Voiceover: Now I reply from one list each morning.',
		'Caption: Now I reply from one list',
		'B-roll: Side-by-side of the old notebook and the new dashboard',
		'',
		'RESULTS',
		`Voiceover: ${results}`,
		`Caption: ${results}`,
		'B-roll: Calendar with completed tasks',
		'',
		'MISSION',
		'Voiceover: I want every client to feel heard.',
		'Caption: Every client feels heard',
		'B-roll: Agent walking past homes on a quiet street',
		'',
		'CALL TO ACTION',
		'Voiceover: Send me a message to talk about your move.',
		'Caption: Send me a message',
		'B-roll: Agent facing the camera with contact details on screen'
	].join('\n');
}

describe('REEL_CHECKLIST', () => {
	it('has the 8 UI-SPEC items in order and the footnote', () => {
		expect(REEL_CHECKLIST).toHaveLength(8);
		expect([...REEL_CHECKLIST]).toEqual(EXPECTED_CHECKLIST);
		expect(REEL_CHECKLIST[1]).toContain(`General Business Law ${SECTION_SIGN} 396-b`);
		expect(REEL_CHECKLIST_FOOTNOTE).toBe(
			"This checklist is a reminder, not legal advice. Check your state's and brokerage's advertising rules."
		);
	});

	it('never claims approval, compliance, guarantees or testimonials', () => {
		for (const line of [...REEL_CHECKLIST, REEL_CHECKLIST_FOOTNOTE]) {
			expect(line).not.toMatch(/testimonial|guarantee|compliant|approved/i);
		}
	});
});

describe('resultsBeatPostCheck', () => {
	it('blocks digits in the results beat when results were left empty', () => {
		const text = script('I helped 47 families.');
		const f = resultsBeatPostCheck(true)(text);
		expect(f).toHaveLength(2);
		// Voiceover and caption each carry one '47'.
		for (const finding of f) {
			expect(text.slice(finding.start, finding.end)).toBe('47');
			expect(finding.severity).toBe('block');
			const m = finding.members[0]!;
			expect(m.categoryLabel).toBe(RESULTS_BEAT_CATEGORY);
			expect(m.categoryLabel).toBe("Result you didn't provide");
			expect(m.explanation).toBe(RESULTS_BEAT_EXPLANATION);
			expect(m.explanation).toBe(
				'You left Your results blank, so this beat must keep the placeholder [Add a real result you can document] and no numbers.'
			);
			expect(m.checker).toBe(REEL_CHECKERS.resultsBeat);
			expect(m.alternative).toBe('');
		}
	});

	it('reports one finding over a results block with only the voiceover number', () => {
		const text = script(RESULTS_PLACEHOLDER).replace(
			`Voiceover: ${RESULTS_PLACEHOLDER}`,
			'Voiceover: I helped 47 families.'
		);
		const f = resultsBeatPostCheck(true)(text);
		expect(f).toHaveLength(1);
		expect(text.slice(f[0]!.start, f[0]!.end)).toBe('47');
	});

	it('blocks the whole beat when the placeholder is missing and there are no digits', () => {
		const text = script('I answer every inquiry quickly.');
		const f = resultsBeatPostCheck(true)(text);
		expect(f).toHaveLength(1);
		expect(text.slice(f[0]!.start, f[0]!.end)).toMatch(/^RESULTS\n[\s\S]*completed tasks$/);
	});

	it('passes a results beat that keeps the placeholder', () => {
		expect(resultsBeatPostCheck(true)(script(RESULTS_PLACEHOLDER))).toEqual([]);
	});

	it('is off when the agent typed results', () => {
		expect(resultsBeatPostCheck(false)(script('I helped 47 families.'))).toEqual([]);
	});

	it('gates every exit through Phase 5 computeGate', () => {
		const findings = runChecks(script('I helped 47 families.'), [resultsBeatPostCheck(true)]);
		expect(computeGate({ phase: 'ready', findings, warnAck: false }).blocked).toBe(true);
	});

	it('with typed results, only the numbers the agent typed are allowed', () => {
		const beats = {
			pain: 'I tracked requests on paper.',
			beforeAfter: 'Now I use one list.',
			results: 'Answered 30 inquiries in 1 week.',
			mission: 'I want every client heard.',
			cta: 'Send me a message.'
		};
		const check = numberPostCheck('reel', reelAllowedNumbers(beats));
		expect(check(script('Answered 30 inquiries in 1 week.'))).toEqual([]);
		const f = check(script('Answered 45 inquiries in 1 week.'));
		expect(f.length).toBeGreaterThan(0);
		expect(f[0]!.members[0]!.categoryLabel).toBe("Number you didn't provide");
	});
});

describe('quotePostCheck', () => {
	it('flags reported client speech for review', () => {
		const text = 'My clients say I answer fast.';
		const f = quotePostCheck()(text);
		expect(f).toHaveLength(1);
		expect(f[0]!.severity).toBe('warn');
		const m = f[0]!.members[0]!;
		expect(m.categoryLabel).toBe(QUOTE_CATEGORY);
		expect(m.categoryLabel).toBe('Quote to confirm');
		expect(m.explanation).toBe(QUOTE_EXPLANATION);
		expect(m.explanation).toBe(
			"This reads like someone else's words. Use a client's words only if they're real and you have their permission."
		);
		expect(m.checker).toBe(REEL_CHECKERS.quotes);
	});

	it('flags an attributed quotation and passes the agent speaking for themself', () => {
		expect(quotePostCheck()('"Best move ever," she said.')).toHaveLength(1);
		expect(quotePostCheck()('I answer every message the same day.')).toEqual([]);
	});

	it('never blocks on its own', () => {
		const findings = runChecks('My clients say I answer fast.', [quotePostCheck()]);
		const gate = computeGate({ phase: 'ready', findings, warnAck: false });
		expect(findings.every((f) => f.severity === 'warn')).toBe(true);
		expect(gate.blocked).toBe(false);
		expect(gate.blockCount).toBe(0);
	});
});

describe('reelFooter', () => {
	it('is the caption disclosure then the checklist as [ ] lines and the footnote', () => {
		expect(reelFooter('DISC')).toBe(
			'ADD TO YOUR POST CAPTION\nDISC\n\nBEFORE YOU POST THIS VIDEO\n' +
				EXPECTED_CHECKLIST.map((item) => `[ ] ${item}\n`).join('') +
				'\n' +
				REEL_CHECKLIST_FOOTNOTE
		);
	});
});

describe('formatReelForExit', () => {
	const footer = reelFooter('Sample Realty, Avery Sample, Licensed Real Estate Salesperson');

	it('formats a parseable draft as the timecoded script ending in the footer', () => {
		const out = formatReelForExit(script(RESULTS_PLACEHOLDER), footer, 30);
		expect(out.startsWith('REEL SCRIPT (30 seconds)')).toBe(true);
		expect(out).toContain('0:00 to 0:03 HOOK');
		expect(out).toContain('0:26 to 0:30 CALL TO ACTION');
		expect(out).toContain('B-ROLL SHOT LIST');
		expect(out).toContain('1. 0:00 Close-up of a phone with unread messages');
		expect(out.endsWith(footer)).toBe(true);
		expect(out.indexOf('B-ROLL SHOT LIST')).toBeLessThan(out.indexOf('ADD TO YOUR POST CAPTION'));
	});

	it('takes times from the 60-second template, never from the model text', () => {
		const draft = script(RESULTS_PLACEHOLDER).replace(
			'Voiceover: I used to lose messages in my inbox.',
			'Voiceover: 0:00 to 0:09 I used to lose messages in my inbox.'
		);
		const out = formatReelForExit(draft, footer, 60);
		expect(out.startsWith('REEL SCRIPT (60 seconds)')).toBe(true);
		expect(out).toContain('0:00 to 0:03 HOOK');
		expect(out).toContain('0:52 to 1:00 CALL TO ACTION');
	});

	it('falls back to the raw draft plus the footer when the draft has no beats', () => {
		const draft = 'Here is a script without beat labels.\n\n';
		const out = formatReelForExit(draft, footer, 30);
		expect(out).toBe(`${draft.trimEnd()}\n\n${footer}`);
		expect(out.endsWith(footer)).toBe(true);
	});

	it('matches the panel formatForExit signature once length is bound', () => {
		const formatForExit: (draft: string, footerText: string) => string = (d, f) =>
			formatReelForExit(d, f, 30);
		expect(formatForExit(script(RESULTS_PLACEHOLDER), footer).endsWith(footer)).toBe(true);
	});
});
